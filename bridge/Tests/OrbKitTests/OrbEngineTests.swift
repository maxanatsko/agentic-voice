import XCTest
@testable import OrbKit

/// The orb engine against values from thinking-orbs' own JavaScript engine (each state, both
/// tuned sizes, three instants): the port must match it number for number.
final class OrbEngineTests: XCTestCase {
    struct Golden {
        let state: OrbState, size: OrbSize, t: Double, dots: Int, lines: Int
        let first: [Double], middle: [Double], last: [Double], firstLine: [Double]?
    }

    func testFramesMatchTheLibrary() {
        for g in Self.golden {
            let p = OrbEngine.preset(g.state, g.size)
            let f = OrbEngine.frame(g.state, size: Double(g.size.rawValue), t: g.t, opts: p.opts)
            let label = "\(g.state) \(g.size) t=\(g.t)"
            XCTAssertEqual(f.dots.count, g.dots, label)
            XCTAssertEqual(f.lines.count, g.lines, label)
            guard f.dots.count == g.dots, f.lines.count == g.lines else { continue }
            func values(_ d: OrbDot) -> [Double] { [d.x, d.y, d.z, d.r, d.white, d.a] }
            for (name, d, want) in [("first", f.dots[0], g.first), ("last", f.dots[g.dots - 1], g.last)] {
                for (a, b) in zip(values(d), want) { XCTAssertEqual(a, b, accuracy: 1e-6, "\(label) \(name)") }
            }
            // Dots at equal depth (the face-on ring) sort by last-bit float noise, which differs
            // between V8's and Darwin's sin/cos, so the middle one is looked up anywhere.
            XCTAssertTrue(f.dots.contains { zip(values($0), g.middle).allSatisfy { abs($0 - $1) < 1e-6 } },
                          "\(label) middle")
            if let want = g.firstLine, let l = f.lines.first {
                let got = [l.x1, l.y1, l.x2, l.y2, l.white, l.a, l.w]
                for (a, b) in zip(got, want) { XCTAssertEqual(a, b, accuracy: 1e-6, "\(label) line") }
            }
        }
    }

